export function cleanString(str: string): string {
  return str
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // remove diacritics / accents except ñ if we keep ñ
    .replace(/[.,/#!$%^&*;:{}=\-_`~()?'"¡¿]/g, '')
    .trim()
    .replace(/\s+/g, ' ');
}

export function isAnswerCorrect(userInput: string, question: QuestionItem): boolean {
  const normalizedInput = cleanString(userInput);
  if (!normalizedInput) return false;

  // Direct normalized check on canonical answer
  if (cleanString(question.answerEs) === normalizedInput) return true;

  // Check acceptable alternatives
  for (const alt of question.acceptableAnswers) {
    if (cleanString(alt) === normalizedInput) return true;
  }

  // Also check if the user typed Armenian translation directly (great for bilingual learners!)
  if (cleanString(question.answerHy) === normalizedInput) return true;

  return false;
}
